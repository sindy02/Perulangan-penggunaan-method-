
public class LatihanPertama {

    public static void main(String[] args) {

        System.out.println("Nomor Urut Barang 1-10");

        for (int i = 1; i <= 10; i++) {
            System.out.println("Barang ke-" + i);
        }

        System.out.println("\nNomor Urut Barang 10-1");

        for (int i = 10; i >= 1; i--) {
            System.out.println("Barang ke-" + i);
        }
    }
}
